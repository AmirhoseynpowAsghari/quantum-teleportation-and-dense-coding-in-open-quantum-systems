def maxdiff(a, b):
    return float(np.max(np.abs(np.asarray(a) - np.asarray(b))))


def entropy_bits_from_eigenvalues(eigenvalues):
    values = np.asarray(eigenvalues)
    values = np.clip(values, 0.0, None)
    nonzero = values > 1e-15
    return float(-np.sum(values[nonzero] * np.log2(values[nonzero])))


def observable_arrays(rho0, t_grid, gamma, Gamma):
    """Vectorized independent amplitude damping of the implemented X states.

    Returns concurrence, singlet fraction, and the Pauli-ensemble Holevo
    quantity. For the latter, equal Pauli encoding on A gives
    rho_bar = (I_A/2) tensor rho_B and chi = 1 + S(rho_B) - S(rho_AB).
    """
    rho0 = np.asarray(rho0)
    p = np.array([p_amplitude_damping(t, gamma, Gamma) for t in t_grid])
    # Shapes are (..., r, 1), with time as the final axis.
    a0 = rho0[..., 0, 0].real[..., None]
    b0 = rho0[..., 1, 1].real[..., None]
    c0 = rho0[..., 2, 2].real[..., None]
    d0 = rho0[..., 3, 3].real[..., None]
    z0 = rho0[..., 1, 2][..., None]

    a = a0 + (1-p)*b0 + (1-p)*c0 + (1-p)**2*d0
    b = p*b0 + p*(1-p)*d0
    c = p*c0 + p*(1-p)*d0
    d = p**2*d0
    z = p*z0

    C = 2*np.maximum(0.0, np.abs(z) - np.sqrt(np.maximum(a*d, 0.0)))
    Fs = np.clip(0.5*(b+c) - z.real, 0.0, 1.0)

    # The evolved states have a diagonal two-entry outer block and a central
    # 2x2 block. b=c for all states generated by the present pipeline.
    if not np.allclose(b, c, atol=2e-12, rtol=0):
        raise ValueError("The analytic central-block reduction requires b=c.")
    eigenvalues = np.stack((a, d, b+z.real, b-z.real), axis=0)
    eigenvalues = np.clip(eigenvalues, 0.0, None)
    nonzero = eigenvalues > 1e-15
    terms = np.zeros_like(eigenvalues, dtype=float)
    terms[nonzero] = eigenvalues[nonzero]*np.log2(eigenvalues[nonzero])
    S_AB = -np.sum(terms, axis=0)

    qB = b+d  # excited-state population of rho_B; rho_B is diagonal here.
    S_B = np.zeros_like(qB, dtype=float)
    for q in (qB, 1-qB):
        mask = q > 1e-15
        S_B[mask] -= q[mask]*np.log2(q[mask])
    S_tilde = 1.0 + S_B
    chi = np.maximum(0.0, S_tilde - S_AB)
    return dict(C=C, Fs=Fs, chi=chi, S_AB=S_AB, S_B=S_B,
                S_tilde=S_tilde, p=p)


def solve_and_build(U):
    bdg = run_selfconsistency(seed=42, U_override=U, verbose=False)
    residual_max = float(np.max(np.abs(bdg["residuals"])))
    if not bdg["converged"] or residual_max > 1e-8:
        raise RuntimeError(f"U={U}: unreliable self-consistency solution; "
                           f"flag={bdg['converged']}, residual={residual_max}")
    r, theta, G, F = compute_greens_functions(
        bdg, verbose=False, convention="legacy_unsigned")
    rho0 = np.asarray(build_density_matrices(G, F))
    if not verify_density_matrices(rho0, atol=2e-8):
        raise RuntimeError(f"U={U}: density-matrix validation failed")
    eigen_min = min(float(np.linalg.eigvalsh(rho).min()) for rho in rho0.reshape(-1, 4, 4))
    return bdg, r, theta, G, F, rho0, residual_max, eigen_min


def validate_against_repository(rho0, r, t_grid, calculated):
    """Directly compare analytic/vectorized formulas with repository routines."""
    errors = dict(C=0.0, Fs=0.0, chi=0.0, pure_fidelity=0.0,
                  trace=0.0, hermiticity=0.0)
    minimum_eigenvalue = np.inf
    for ir in np.linspace(0, len(r)-1, 7, dtype=int):
        for it in np.linspace(0, len(t_grid)-1, 9, dtype=int):
            rho = evolve_rho(rho0[3, ir], float(t_grid[it]), kind="amp",
                             bath="independent", gammaA=LOW["gamma"],
                             GammaA=LOW["Gamma"], gammaB=LOW["gamma"],
                             GammaB=LOW["Gamma"])
            errors["C"] = max(errors["C"], abs(calculated["C"][3, ir, it]-concurrence_xstate(rho)))
            errors["Fs"] = max(errors["Fs"], abs(calculated["Fs"][3, ir, it]-singlet_fraction(rho)))
            chi, _, _ = compute_holevo(rho)
            errors["chi"] = max(errors["chi"], abs(calculated["chi"][3, ir, it]-chi))
            psi = np.array([0, 1, -1, 0], dtype=complex)/np.sqrt(2)
            pure = np.outer(psi, psi.conj())
            errors["pure_fidelity"] = max(
                errors["pure_fidelity"],
                abs(calculated["Fs"][3, ir, it]-fidelity_uhlmann(rho, pure)))
            errors["trace"] = max(errors["trace"], abs(rho.trace().real-1))
            errors["hermiticity"] = max(errors["hermiticity"],
                                        float(np.max(np.abs(rho-rho.conj().T))))
            minimum_eigenvalue = min(minimum_eigenvalue,
                                     float(np.linalg.eigvalsh(rho).min()))
    errors["minimum_eigenvalue"] = minimum_eigenvalue
    return errors


def plot_delta_heatmaps(solutions):
    U_values = [40, 75, 115]
    fig, axes = plt.subplots(1, 3, figsize=(13, 4.2), constrained_layout=True)
    images = []
    lim = max(float(np.max(np.abs(solutions[U]["bdg"]["Delta_ks"][:, :, 0])))
              for U in U_values)
    for ax, U in zip(axes, U_values):
        bdg = solutions[U]["bdg"]
        gap = bdg["Delta_ks"][:, :, 0]
        im = ax.imshow(gap, origin="lower", cmap="RdBu_r", vmin=-lim, vmax=lim,
                       extent=[-np.pi, np.pi, -np.pi, np.pi], aspect="equal")
        images.append(im)
        ax.set_title(fr"$U/t={U}$")
        ax.set_xlabel(r"$k_x$")
        ax.set_ylabel(r"$k_y$")
        ax.text(0.03, 0.03,
                fr"$\Delta_0={bdg['Delta0']:.4f}t$" "\n" fr"$\Delta_s={bdg['DeltaS']:.4f}t$",
                transform=ax.transAxes, fontsize=8,
                bbox=dict(facecolor="white", alpha=0.75, edgecolor="none"))
    fig.colorbar(images[-1], ax=axes, shrink=0.85, label=r"$\Delta_{\mathbf{k},s=+1}/t$")
    fig.savefig(ROOT / "Delta_ks_heatmaps.png", dpi=180, bbox_inches="tight")
    plt.close(fig)


def plot_greens_angular(U, solution):
    r = solution["r"]
    theta = solution["theta"]
    G = solution["G"]
    F = solution["F"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), constrained_layout=True)
    for angle in (0, 30, 60, 90):
        i = int(np.argmin(np.abs(np.degrees(theta)-angle)))
        axes[0].plot(r, np.abs(G[i]), label=fr"$\theta={angle}^\circ$")
        axes[1].plot(r, np.abs(F[i]), label=fr"$\theta={angle}^\circ$")
    axes[0].set_ylabel(r"$|G_{\uparrow\uparrow}(r,\theta)|$")
    axes[1].set_ylabel(r"$|F_{\uparrow\downarrow}(r,\theta)|$")
    for ax in axes:
        ax.set_xlabel(r"$r$")
        ax.set_xlim(r[0], r[-1])
        ax.grid(alpha=0.25)
        ax.legend()
    fig.suptitle(fr"Implemented magnitude-amplitude correlators, $U/t={U}$")
    fig.savefig(FIGS / "greens_angular.png", dpi=180, bbox_inches="tight")
    plt.close(fig)


def plot_concurrence_U_theta(solutions):
    U_values = [20, 44, 79, 115]
    angles = [0, 30, 60, 90]
    fig, axes = plt.subplots(2, 2, figsize=(11, 7.5), sharex=True, sharey=True,
                             constrained_layout=True)
    for ax, angle in zip(axes.flat, angles):
        for U in U_values:
            sol = solutions[U]
            i = int(np.argmin(np.abs(np.degrees(sol["theta"])-angle)))
            C = sol["initial_obs"]["C"][i, :, 0]
            ax.plot(sol["r"], C, label=fr"$U/t={U}$")
        ax.set_title(fr"$\theta={angle}^\circ$")
        ax.set_xlim(0, 4)
        ax.set_ylim(0, 1.02)
        ax.grid(alpha=0.25)
        ax.legend(fontsize=8)
    for ax in axes[-1]:
        ax.set_xlabel(r"$r$")
    for ax in axes[:, 0]:
        ax.set_ylabel(r"$C(r,\theta,t=0)$")
    fig.savefig(FIGS / "concurrence_U_theta.png", dpi=180, bbox_inches="tight")
    plt.close(fig)


def plot_U_sweep(U_values, r, t_grid, C, Fs, chi):
    ir = int(np.argmin(np.abs(r-1.5)))
    ith = 3  # 45 degrees, matching the low-noise radial and temporal figures.
    fig, axes = plt.subplots(2, 2, figsize=(11, 7.5), constrained_layout=True)
    for iU, U in enumerate(U_values):
        label = fr"$U/t={U:g}$"
        axes[0, 0].plot(r, Fs[iU, ith, :, 0], label=label)
        axes[0, 1].plot(r, chi[iU, ith, :, 0], label=label)
        axes[1, 0].plot(t_grid, Fs[iU, ith, ir, :], label=label)
        axes[1, 1].plot(t_grid, chi[iU, ith, ir, :], label=label)
    axes[0, 0].set_ylabel(r"$\mathcal{F}_{\Psi^-}(r,45^\circ,0)$")
    axes[0, 1].set_ylabel(r"$\chi(r,45^\circ,0)$ [bits]")
    axes[1, 0].set_ylabel(fr"$\mathcal{{F}}_{{\Psi^-}}(r={r[ir]:.2f},45^\circ,t)$")
    axes[1, 1].set_ylabel(fr"$\chi(r={r[ir]:.2f},45^\circ,t)$ [bits]")
    axes[1, 0].set_ylim(0, 1.02)
    axes[1, 1].set_ylim(0, 2.02)
    for ax in axes.flat:
        ax.grid(alpha=0.25)
        ax.legend()
    for ax in axes[0]:
        ax.set_xlabel(r"$r$")
        ax.set_xlim(0, 6)
    for ax in axes[1]:
        ax.set_xlabel(r"$t$")
        ax.set_xlim(t_grid[0], t_grid[-1])
    fig.savefig(FIGS / "U_dependence_fidelity_holevo.png", dpi=180,
                bbox_inches="tight")
    plt.close(fig)
    return int(ir)


def main():
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT,
                                     text=True).strip()
    solutions = {}
    validation = {
        "repository_commit": commit,
        "implementation_scope": (
            "Current magnitude-amplitude Green's-function implementation; "
            "the signed Delta/(2E) coherence factor is not used by greens_functions.py."
        ),
        "python": {"numpy": np.__version__},
    }

    # The U=75 solution is the common provenance check for all archived data.
    print("Recomputing U/t=75 Green's functions and observables ...")
    bdg, r, theta, G, F, rho0, residual, eigen_min = solve_and_build(75)
    solutions[75] = dict(bdg=bdg, r=r, theta=theta, G=G, F=F, rho0=rho0,
                         residual=residual, eigen_min=eigen_min)
    t_low = np.linspace(config.T_MIN, config.T_MAX, config.N_T)
    low = observable_arrays(rho0, t_low, **LOW)
    solutions[75]["initial_obs"] = observable_arrays(rho0, np.array([0.0]), **LOW)

    validation["r0_amplitude_damping_identity_max_abs_error"] = {
        "low_Fs_minus_p": maxdiff(low["Fs"][:, 0, :], low["p"]),
        "low_C_minus_p": maxdiff(low["C"][:, 0, :], low["p"]),
    }

    # The current legacy mode includes the common single-spin helicity factor
    # 1/2.  Multiply by two when comparing raw arrays with the old archive.
    with np.load(DATA / f"{LOW_PREFIX}_greens.npz") as d:
        validation["archived_low_greens_max_abs_error"] = {
            "G": maxdiff(2.0*G, d["G_t"][:, :, 0]),
            "F": maxdiff(2.0*F, d["F_t"][:, :, 0])}
    with np.load(DATA / f"{HIGH_PREFIX}_greens.npz") as d:
        validation["archived_high_greens_max_abs_error"] = {
            "G": maxdiff(2.0*G, d["G_t"][:, :, 0]),
            "F": maxdiff(2.0*F, d["F_t"][:, :, 0])}

    with np.load(DATA / f"{LOW_PREFIX}_theta_obs.npz") as d:
        validation["archived_low_observable_max_abs_error"] = {
            "C_all": maxdiff(low["C"], d["C_all"]),
            "Fs_all": maxdiff(low["Fs"], d["Fs_all"]),
            "F_pure": maxdiff(low["Fs"], d["F_pure"]),
        }
        validation["archived_fidelity_bounds"] = {
            "F_init_min": float(d["F_init"].min()), "F_init_max": float(d["F_init"].max()),
            "F_pure_min": float(d["F_pure"].min()), "F_pure_max": float(d["F_pure"].max()),
            "F_init_t0_max_error": float(np.max(np.abs(d["F_init"][:, :, 0]-1))),
        }
        validation["angular_symmetry_max_abs_error"] = {
            "C_0_minus_90": maxdiff(d["C_all"][0], d["C_all"][6]),
            "F_0_minus_90": maxdiff(d["F_pure"][0], d["F_pure"][6]),
            "F_15_minus_75": maxdiff(d["F_pure"][1], d["F_pure"][5]),
            "F_30_minus_60": maxdiff(d["F_pure"][2], d["F_pure"][4]),
        }
        validation["r0_angular_variation"] = {
            "C_ptp_max_over_t": float(np.max(np.ptp(d["C_all"][:, 0, :], axis=0))),
            "F_ptp_max_over_t": float(np.max(np.ptp(d["F_pure"][:, 0, :], axis=0))),
        }

    with np.load(DATA / f"{LOW_PREFIX}_holevo.npz") as d:
        validation["archived_low_holevo_max_abs_error"] = {
            "chi_all": maxdiff(low["chi"], d["chi_all"]),
            "S_rho_all": maxdiff(low["S_AB"], d["S_rho_all"]),
            "S_tilde_all": maxdiff(low["S_tilde"], d["S_tilde_all"]),
            "chi_rt": maxdiff(low["chi"][3], d["chi_rt"]),
        }
        validation["holevo_bounds"] = {
            "chi_min": float(d["chi_all"].min()), "chi_max": float(d["chi_all"].max()),
            "S_rho_min": float(d["S_rho_all"].min()), "S_rho_max": float(d["S_rho_all"].max()),
            "S_tilde_min": float(d["S_tilde_all"].min()), "S_tilde_max": float(d["S_tilde_all"].max()),
            "r0_angular_ptp_max": float(np.max(np.ptp(d["chi_all"][:, 0, :], axis=0))),
            "final_time_max_abs_deviation_from_1": float(np.max(np.abs(d["chi_all"][:, :, -1]-1))),
        }

    # High-noise data use 161 times rather than the current 261-point default.
    with np.load(DATA / f"{HIGH_PREFIX}_fidelity.npz") as d:
        t_high = d["t_grid"]
        high = observable_arrays(rho0, t_high, **HIGH)
        validation["archived_high_fidelity_max_abs_error"] = {
            "F_pure": maxdiff(high["Fs"][0], d["F_pure"])}
        validation["high_fidelity_bounds"] = {
            "F_init_min": float(d["F_init"].min()), "F_init_max": float(d["F_init"].max()),
            "F_pure_min": float(d["F_pure"].min()), "F_pure_max": float(d["F_pure"].max()),
            "F_init_t0_max_error": float(np.max(np.abs(d["F_init"][:, 0]-1))),
        }
        validation["high_regime_C_range"] = {
            "min": float(high["C"].min()), "max": float(high["C"].max())}
        validation["r0_amplitude_damping_identity_max_abs_error"].update({
            "high_Fs_minus_p": maxdiff(high["Fs"][:, 0, :], high["p"]),
            "high_C_minus_p": maxdiff(high["C"][:, 0, :], high["p"]),
        })

    validation["direct_repository_crosscheck"] = validate_against_repository(
        rho0, r, t_low, low)

    # Additional interaction calculations use precisely the three U values
    # already introduced in the unfinished manuscript.
    U_values = [40, 75, 115]
    for U in (40, 115):
        print(f"Computing U/t={U} ...")
        solutions[U] = dict(zip(
            ("bdg", "r", "theta", "G", "F", "rho0", "residual", "eigen_min"),
            solve_and_build(U)))
        solutions[U]["initial_obs"] = observable_arrays(
            solutions[U]["rho0"], np.array([0.0]), **LOW)

    # Supporting initial-concurrence plot values from the existing manuscript.
    # U=150 is intentionally excluded: tested solutions did not meet the
    # residual criterion, which is recorded in the scientific audit.
    for U in (20, 44, 79):
        print(f"Computing initial state for U/t={U} ...")
        solutions[U] = dict(zip(
            ("bdg", "r", "theta", "G", "F", "rho0", "residual", "eigen_min"),
            solve_and_build(U)))
        solutions[U]["initial_obs"] = observable_arrays(
            solutions[U]["rho0"], np.array([0.0]), **LOW)

    C = np.stack([observable_arrays(solutions[U]["rho0"], t_low, **LOW)["C"]
                  for U in U_values])
    Fs = np.stack([observable_arrays(solutions[U]["rho0"], t_low, **LOW)["Fs"]
                   for U in U_values])
    chi = np.stack([observable_arrays(solutions[U]["rho0"], t_low, **LOW)["chi"]
                    for U in U_values])
    S_AB = np.stack([observable_arrays(solutions[U]["rho0"], t_low, **LOW)["S_AB"]
                     for U in U_values])
    S_B = np.stack([observable_arrays(solutions[U]["rho0"], t_low, **LOW)["S_B"]
                    for U in U_values])

    sweep_path = DATA / "hubbard_U40_U75_U115_amp_independent_g1.50_G0.100_observables.npz"
    np.savez_compressed(
        sweep_path,
        U_values=np.array(U_values, dtype=float), r_vals=r, t_grid=t_low,
        theta_vals=theta, C=C, F_singlet=Fs, chi=chi, S_AB=S_AB, S_B=S_B,
        Delta0=np.array([solutions[U]["bdg"]["Delta0"] for U in U_values]),
        DeltaS=np.array([solutions[U]["bdg"]["DeltaS"] for U in U_values]),
        mu=np.array([solutions[U]["bdg"]["mu"] for U in U_values]),
        residuals=np.array([solutions[U]["residual"] for U in U_values]),
        density_min_eigenvalue=np.array([solutions[U]["eigen_min"] for U in U_values]),
        t_hop=config.t_hop, Delta_t=config.Delta_t, V_SO=config.V_SO,
        n_elec=config.n_elec, Nk=config.Nk, gamma=LOW["gamma"], Gamma=LOW["Gamma"],
        noise_kind=np.bytes_("amp"), noise_bath=np.bytes_("independent"),
        implementation=np.bytes_("magnitude-amplitude archived convention"),
        repository_commit=np.bytes_(commit),
    )

    validation["U_sweep"] = {
        "data_file": str(sweep_path.relative_to(ROOT)),
        "fixed_parameters": {
            "Delta_t_over_t": config.Delta_t/config.t_hop,
            "V_SO_over_t": config.V_SO/config.t_hop,
            "n_elec": config.n_elec, "Nk": config.Nk,
            "gamma_over_t": LOW["gamma"], "Gamma_over_t": LOW["Gamma"],
            "r_points": len(r), "time_points": len(t_low),
            "theta_degrees": np.degrees(theta).tolist(),
        },
        "solutions": {
            str(U): {
                "Delta0_over_t": solutions[U]["bdg"]["Delta0"],
                "DeltaS_over_t": solutions[U]["bdg"]["DeltaS"],
                "mu_over_t": solutions[U]["bdg"]["mu"],
                "max_absolute_residual": solutions[U]["residual"],
                "initial_density_matrix_min_eigenvalue": solutions[U]["eigen_min"],
                "C_range": [float(C[i].min()), float(C[i].max())],
                "F_singlet_range": [float(Fs[i].min()), float(Fs[i].max())],
                "chi_range": [float(chi[i].min()), float(chi[i].max())],
            } for i, U in enumerate(U_values)
        },
    }

    # Concise, reproducible numerical summaries used while writing the text.
    ir15 = int(np.argmin(np.abs(r-1.5)))
    validation["U_sweep_fixed_slice_r_index"] = ir15
    validation["U_sweep_fixed_slice_r"] = float(r[ir15])
    validation["U_sweep_initial_theta45"] = {
        str(U): {
            "Fs_r0": float(Fs[i, 3, 0, 0]),
            "chi_r0": float(chi[i, 3, 0, 0]),
            "Fs_fixed_r_t0": float(Fs[i, 3, ir15, 0]),
            "chi_fixed_r_t0": float(chi[i, 3, ir15, 0]),
            "Fs_fixed_r_t80": float(Fs[i, 3, ir15, -1]),
            "chi_fixed_r_t80": float(chi[i, 3, ir15, -1]),
            "C_max_r": float(r[np.argmax(C[i, 3, :, 0])]),
            "largest_initial_Fs_at_nonzero_r": float(Fs[i, 3, 1:, 0].max()),
        } for i, U in enumerate(U_values)
    }

    print("Generating manuscript support figures ...")
    plot_delta_heatmaps(solutions)
    plot_greens_angular(75, solutions[75])
    plot_concurrence_U_theta(solutions)
    plot_U_sweep(U_values, r, t_low, C, Fs, chi)

    with open(REPORTS / "numerical_validation.json", "w", encoding="utf-8") as handle:
        json.dump(validation, handle, indent=2)
    print(json.dumps(validation, indent=2))
    print(f"Saved {sweep_path}")
    print(f"Saved {REPORTS / 'numerical_validation.json'}")


if __name__ == "__main__":
    main()
